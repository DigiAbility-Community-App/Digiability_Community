#!/usr/bin/env node
/**
 * sync:legal — generate the app-side legal document modules from docs/legal/.
 *
 * docs/legal/ is the single source of truth. Both clients previously kept their
 * own hand-written copies of the Privacy Policy and Terms (LegalScreen.tsx and
 * apps/web/src/features/legal/*.tsx), and those two copies had already drifted
 * apart. Generating instead means one edit updates every surface, and the policy
 * version that drives re-acceptance cannot disagree with the text it refers to.
 *
 * Metro cannot import .md without extra config and Vite needs ?raw, so rather
 * than fight two bundlers we emit plain TypeScript modules.
 *
 * Run after editing anything in docs/legal/. Wired as `npm run sync:legal`, and as a
 * prebuild step in apps/web so a build can never ship stale policy text.
 *
 * Output paths deliberately avoid any directory named "generated" — .gitignore carries a
 * recursive ignore rule on that directory name for Prisma client output, which would
 * silently exclude these files and break the legal screens on a fresh clone.
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const LEGAL_DIR = path.join(ROOT, "docs", "legal");
const MANIFEST = path.join(LEGAL_DIR, "manifest.json");

const BANNER = `// AUTO-GENERATED by scripts/sync-legal-docs.js — DO NOT EDIT BY HAND.
// Source: docs/legal/  •  Regenerate with: npm run sync:legal
`;

function loadManifest() {
  const manifest = JSON.parse(fs.readFileSync(MANIFEST, "utf8"));
  const docs = manifest.documents.map((doc) => {
    const full = path.join(LEGAL_DIR, doc.file);
    if (!fs.existsSync(full)) {
      console.error(`sync:legal — manifest lists ${doc.file}, which does not exist`);
      process.exit(1);
    }
    return { ...doc, markdown: fs.readFileSync(full, "utf8") };
  });
  if (!manifest.consentNoticeVersion) {
    console.error("sync:legal — manifest.json is missing consentNoticeVersion");
    process.exit(1);
  }
  return { policyVersion: manifest.policyVersion, consentNoticeVersion: manifest.consentNoticeVersion, docs };
}

function renderClientModule({ policyVersion, consentNoticeVersion, docs }) {
  const ids = docs.map((d) => JSON.stringify(d.id)).join(" | ");
  const slugs = docs.map((d) => JSON.stringify(d.slug)).join(" | ");
  const entries = docs
    .map(
      (d) => `  ${JSON.stringify(d.id)}: {
    id: ${JSON.stringify(d.id)},
    title: ${JSON.stringify(d.title)},
    slug: ${JSON.stringify(d.slug)},
    requiresAcceptance: ${d.requiresAcceptance},
    markdown: ${JSON.stringify(d.markdown)},
  },`
    )
    .join("\n");

  return `${BANNER}
/** Version of the published policy set. Drives consent records and re-acceptance. */
export const POLICY_VERSION = ${JSON.stringify(policyVersion)};

/** Version of the data-processing consent notice (DPDP §5). Stamped on the
 * DATA_PROCESSING consent record; changing it re-asks only that consent. */
export const CONSENT_NOTICE_VERSION = ${JSON.stringify(consentNoticeVersion)};

export type LegalDocId = ${ids};

/** Literal union so a mistyped slug fails to compile rather than rendering a
 * "not found" screen at runtime. */
export type LegalDocSlug = ${slugs};

export interface LegalDoc {
  id: LegalDocId;
  title: string;
  /** URL path segment on the web, and route param on mobile. */
  slug: LegalDocSlug;
  /** True for the documents a user must accept before creating content. */
  requiresAcceptance: boolean;
  markdown: string;
}

export const LEGAL_DOCS: Record<LegalDocId, LegalDoc> = {
${entries}
};

/** Documents a user must accept, in the order they are presented. */
export const ACCEPTANCE_REQUIRED: LegalDoc[] = Object.values(LEGAL_DOCS).filter(
  (d) => d.requiresAcceptance
);

export const ALL_LEGAL_DOCS: LegalDoc[] = Object.values(LEGAL_DOCS);

export function getLegalDocBySlug(slug: string): LegalDoc | undefined {
  return ALL_LEGAL_DOCS.find((d) => d.slug === slug);
}
`;
}

function renderServerModule({ policyVersion, consentNoticeVersion }) {
  return `${BANNER}
// The server never needs the document text — only the version it must stamp on
// consent records and compare against to decide whether re-acceptance is due.

/** Version of the published policy set. Must match docs/legal/manifest.json. */
export const POLICY_VERSION = ${JSON.stringify(policyVersion)};

/** Version of the data-processing consent notice. Must match docs/legal/manifest.json. */
export const CONSENT_NOTICE_VERSION = ${JSON.stringify(consentNoticeVersion)};
`;
}

function write(target, contents) {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  const existing = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;
  if (existing === contents) {
    console.log(`  unchanged  ${path.relative(ROOT, target)}`);
    return false;
  }
  fs.writeFileSync(target, contents, "utf8");
  console.log(`  written    ${path.relative(ROOT, target)}`);
  return true;
}

function main() {
  const data = loadManifest();
  const client = renderClientModule(data);
  const server = renderServerModule(data);

  console.log(`sync:legal — policy version ${data.policyVersion}, consent notice ${data.consentNoticeVersion}, ${data.docs.length} documents`);
  write(path.join(ROOT, "apps", "mobile", "src", "legal", "legal-docs.generated.ts"), client);
  write(path.join(ROOT, "apps", "web", "src", "legal", "legal-docs.generated.ts"), client);
  write(
    path.join(ROOT, "services", "user-svc", "src", "config", "policy-version.generated.ts"),
    server
  );
  console.log("sync:legal done.");
}

main();
